// Writes src/content/docs/docs/diagnostics.md from docs/errors.md, so the
// error reference has one source: the file the compiler itself holds.
import { readFileSync, writeFileSync } from 'node:fs';

const source = readFileSync(new URL('../../docs/errors.md', import.meta.url), 'utf-8').replace(/\r\n/g, '\n');
const first = source.indexOf('\n## ');
const ranges = source.match(/^The ranges are:.*$/m)?.[0] ?? '';
if (first < 0 || !ranges) throw new Error('docs/errors.md no longer has the expected shape');

const page = `---
title: Compiler diagnostics
description: Every Lucid compile error code, with its cause, an example, and a fix.
---

<!-- Generated by scripts/sync-docs.mjs from docs/errors.md. Do not edit. -->

Every compile error has a stable code. A code never changes meaning once released. Each entry below gives the cause, an example that produces it, and a fix. The same text is built into the compiler:

\`\`\`sh
lucid explain E0303
lucid explain --json E0303
\`\`\`

${ranges}

The examples on this page are wrong on purpose: each one produces its own code.
${source.slice(first)}`;

writeFileSync(new URL('../src/content/docs/docs/diagnostics.md', import.meta.url), page);
console.log('wrote src/content/docs/docs/diagnostics.md');
